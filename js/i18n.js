let currentLanguage = 'pt';

/**
 * Retorna o idioma atualmente ativo
 * @returns {'pt'|'en'}
 */
function getCurrentLanguage() {
    return currentLanguage;
}

/**
 * Busca a tradução pela chave no idioma ativo
 * @param {string} key 
 * @returns {string}
 */
function getTranslation(key) {
    const langObj = TRANSLATIONS[currentLanguage] || TRANSLATIONS.pt;
    return langObj[key] || key;
}

/**
 * Aplica os textos traduzidos em todos os elementos da página
 * @param {'pt'|'en'} lang 
 */
function applyTranslations(lang) {
    currentLanguage = (lang === 'en') ? 'en' : 'pt';
    const dict = TRANSLATIONS[currentLanguage];

    // Atualizar atributo lang no html
    document.documentElement.lang = (currentLanguage === 'pt') ? 'pt-BR' : 'en';

    // Atualizar título da página
    if (dict.page_title) {
        document.title = dict.page_title;
    }

    // Elementos com data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key] !== undefined) {
            el.textContent = dict[key];
        }
    });

    // Elementos com data-i18n-html (para conteúdos com tags como <br>)
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
        const key = el.getAttribute('data-i18n-html');
        if (dict[key] !== undefined) {
            el.innerHTML = dict[key];
        }
    });

    // Elementos com data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key] !== undefined) {
            el.setAttribute('placeholder', dict[key]);
        }
    });

    // Atualizar classes ativas nos botões de idioma
    const btnPt = document.getElementById('lang-pt');
    const btnEn = document.getElementById('lang-en');

    if (btnPt && btnEn) {
        if (currentLanguage === 'pt') {
            btnPt.classList.add('active');
            btnPt.setAttribute('aria-pressed', 'true');
            btnEn.classList.remove('active');
            btnEn.setAttribute('aria-pressed', 'false');
        } else {
            btnEn.classList.add('active');
            btnEn.setAttribute('aria-pressed', 'true');
            btnPt.classList.remove('active');
            btnPt.setAttribute('aria-pressed', 'false');
        }
    }

    // Atualizar grid de produtos, resumo do carrinho e botão de pedido com os novos textos
    if (typeof renderProductsGrid === 'function') {
        renderProductsGrid();
    }
    if (typeof renderCartSummary === 'function') {
        renderCartSummary();
    }
    if (typeof updateOrderButton === 'function') {
        updateOrderButton();
    }
}

/**
 * Alterna o idioma do aplicativo e salva no localStorage
 * @param {'pt'|'en'} lang 
 * @param {boolean} showNotification 
 */
function switchLanguage(lang, showNotification = true) {
    if (lang !== 'pt' && lang !== 'en') return;
    
    currentLanguage = lang;
    try {
        localStorage.setItem('sabor_mineiro_lang', lang);
    } catch (e) {
        // Fallback silencioso caso cookies/storage estejam bloqueados
    }

    applyTranslations(lang);

    if (showNotification && typeof showToast === 'function') {
        showToast(getTranslation('toast_lang_switched'), 'success');
    }
}

/**
 * Inicializa a detecção de idioma no carregamento
 */
function initLanguage() {
    let saved = 'pt';
    try {
        saved = localStorage.getItem('sabor_mineiro_lang') || 'pt';
    } catch (e) {
        saved = 'pt';
    }

    // Se o usuário não tiver preferência salva mas o navegador for inglês, pode iniciar em inglês
    if (!localStorage.getItem('sabor_mineiro_lang')) {
        const navLang = (navigator.language || navigator.userLanguage || '').toLowerCase();
        if (navLang.startsWith('en')) {
            saved = 'en';
        }
    }

    switchLanguage(saved, false);
}
